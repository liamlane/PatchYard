def host_ip_exec(props: dict) -> list[str]:
    ip = props.get("ip_mode", "none")
    cmds = ["ip route del default"]
    if ip == "static" and props.get("ip"):
        cmds.append(f"ip addr add {check_ip(props['ip'], cidr=True)} dev eth1")
        if props.get("gateway"):
            cmds.append(f"ip route replace default via {check_ip(props['gateway'])} dev eth1")
        if props.get("dns"):
            cmds.append(f'sh -c "echo nameserver {check_ip(props["dns"])} > /etc/resolv.conf"')
    elif ip == "dhcp":
        # sends its hostname so the server's DHCP lease table shows who has which address
        cmds.append('sh -c "udhcpc -i eth1 -b -q -x hostname:$(hostname) -s /usr/local/bin/netlab-dhcp"')
    return cmds


MAC_RE = re.compile(r"^([0-9a-fA-F]{2}[:-]){5}[0-9a-fA-F]{2}$")
LEASE_RE = re.compile(r"^(\d+)([mhd]?)$|^infinite$")


def dnsmasq_conf(props: dict) -> str:
    svc = props.get("services", {})
    dns = svc.get("dns", {})
    dhcp = svc.get("dhcp", {})
    # bind-dynamic (not bind-interfaces): the server's eth1 address is usually set from
    # Desktop > IP Configuration after deploy, and dnsmasq must start answering on it.
    # The lease file lives in the svc bind mount so the web UI can list leases.
    lines = ["# generated by netlab", "no-resolv", "no-hosts", "interface=eth1", "bind-dynamic", "log-queries",
             "dhcp-leasefile=/etc/netlab/svc/dnsmasq.leases"]
    if dns.get("enabled"):
        # local=/#/ + host-record: authoritative answers (NXDOMAIN / NODATA). With
        # address=/ and no upstream, dnsmasq REFUSES AAAA and musl (Alpine) PCs fail.
        lines.append("local=/#/")
        names = set()
        for r in dns.get("records", []):
            if r.get("type", "A") == "A":
                names.add(check_host(r["name"]).lower())
                lines.append(f"host-record={r['name']},{check_ip(r['ip'])}")
        for r in dns.get("records", []):
            if r.get("type") == "CNAME":
                tgt = check_host(r.get("target") or r.get("ip") or "")
                if tgt.lower() not in names:
                    raise ValueError(f"DNS: CNAME {r['name']} points at {tgt}, which needs its own A record on this server")
                lines.append(f"cname={check_host(r['name'])},{tgt}")
            elif r.get("type", "A") != "A":
                raise ValueError(f"DNS: record type {r.get('type')} isn't supported (A or CNAME)")
    else:
        lines.append("port=0")
    if dhcp.get("enabled"):
        lease = str(dhcp.get("lease") or "12h").strip()
        if not LEASE_RE.match(lease):
            raise ValueError("DHCP lease time: e.g. 30m, 12h, 7d or infinite")
        lines.append(f"dhcp-range={check_ip(dhcp['start'])},{check_ip(dhcp['end'])},{check_ip(dhcp.get('mask') or '255.255.255.0')},{lease}")
        if dhcp.get("gateway"):
            lines.append(f"dhcp-option=3,{check_ip(dhcp['gateway'])}")
        if dhcp.get("dns"):
            lines.append(f"dhcp-option=6,{check_ip(dhcp['dns'])}")
        if dhcp.get("domain"):
            lines.append(f"dhcp-option=15,{check_host(dhcp['domain'])}")
        if dhcp.get("tftp"):
            # option 150 (Cisco IP phones / Packet Tracer) and 66 (everyone else)
            lines += [f"dhcp-option=150,{check_ip(dhcp['tftp'])}", f"dhcp-option=66,{check_ip(dhcp['tftp'])}"]
        seen = set()
        for r in dhcp.get("reservations") or []:
            mac = str(r.get("mac", "")).strip().lower().replace("-", ":")
            if not MAC_RE.match(mac):
                raise ValueError(f"DHCP reservation: '{r.get('mac')}' isn't a MAC address (aa:bb:cc:dd:ee:ff)")
            if mac in seen:
                raise ValueError(f"DHCP reservation: {mac} twice")
            seen.add(mac)
            name = f",{check_host(r['name'])}" if r.get("name") else ""
            lines.append(f"dhcp-host={mac},{check_ip(r['ip'])}{name}")
    return "\n".join(lines) + "\n"


def leases(text: str) -> list[dict]:
    """dnsmasq lease file -> [{expires, mac, ip, host}]"""
    out = []
    for line in text.splitlines():
        f = line.split()
        if len(f) >= 4:
            out.append({"expires": int(f[0]) if f[0].isdigit() else 0, "mac": f[1], "ip": f[2], "host": "" if f[3] == "*" else f[3]})
    return out


