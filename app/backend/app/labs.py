def load(name: str) -> dict:
    f = lab_dir(name) / "lab.json"
    if not f.exists():
        raise FileNotFoundError(f"lab '{name}' not found")
    return json.loads(f.read_text())


def save(lab: dict):
    check_name(lab["name"])
    for l in lab.get("links", []):
        check_name(l["a"]); check_name(l["b"]); check_if(l["a_if"]); check_if(l["b_if"])
        if l.get("media", "copper") not in hardware.MEDIA:
            raise ValueError(f"unknown cable media {l.get('media')}")
    for n in lab.get("nodes", []):
        check_name(n["id"])
        if n.get("type") not in ("router", "switch", "pc", "server", "firewall"):
            raise ValueError(f"unknown device type {n.get('type')}")
        hardware.validate(n, lab.get("links", []))
        if n["type"] == "firewall" and not n.get("raw"):
            firewall.normalise(n.get("props") or {})
        if n["type"] == "server" and not n.get("raw"):
            validate_server(n.get("props") or {})
    anns = []
    for a in lab.get("annotations", []) or []:
        if a.get("kind") not in ("note", "area") or not re.fullmatch(r"ann-[\w-]{1,40}", str(a.get("id", ""))):
            raise ValueError("bad annotation")
        anns.append({"id": a["id"], "kind": a["kind"], "x": float(a.get("x", 0)), "y": float(a.get("y", 0)),
                     "w": max(60.0, min(4000.0, float(a.get("w", 200)))), "h": max(40.0, min(4000.0, float(a.get("h", 120)))),
                     "text": str(a.get("text", ""))[:2000], "color": str(a.get("color", "yellow"))[:20]})
    lab["annotations"] = anns
    d = lab_dir(lab["name"])
    d.mkdir(parents=True, exist_ok=True)
    (d / "lab.json").write_text(json.dumps(lab, indent=2))


def patch_props(name: str, node_id: str, fn) -> dict:
    """Load, change one device's props with fn(props), save, and bump the revision."""
    lab = load(name)
    node = next((n for n in lab["nodes"] if n["id"] == node_id), None)
    if not node:
        raise FileNotFoundError(f"device '{node_id}' not in lab")
    fn(node.setdefault("props", {}))
    save(lab)
    REV[name] = REV.get(name, 0) + 1
    NODE_REV[(name, node_id)] = REV[name]
    return node


def rev_info(name: str) -> dict:
    return {"rev": REV.get(name, 0), "rev_nodes": {n: r for (l, n), r in NODE_REV.items() if l == name}}


def create(name: str) -> dict:
    if (lab_dir(name) / "lab.json").exists():
        raise FileExistsError(f"lab '{name}' already exists")
    lab = {"name": name, "mgmt_network": _d("mgmt_network"), "mgmt_subnet": _d("mgmt_subnet"), "nodes": [], "links": []}
    save(lab)
    return lab


