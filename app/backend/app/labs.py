def vlan_id(v) -> int:
    v = int(v)
    if not 1 <= v <= 4094:
        raise ValueError(f"VLAN {v} out of range 1-4094")
    return v


def vlan_list(text) -> list[int]:
    """'10,20,30-32' -> [10, 20, 30, 31, 32]"""
    out = []
    for part in str(text or "").replace(" ", "").split(","):
        if not part:
            continue
        if "-" in part:
            a, b = (vlan_id(x) for x in part.split("-", 1))
            if b < a or b - a > 4093:
                raise ValueError(f"bad VLAN range {part}")
            out += range(a, b + 1)
        else:
            out.append(vlan_id(part))
    return sorted(set(out))


def _expand(vs) -> str:
    return ",".join(str(v) for v in vs)


def ovs_script(node: dict) -> str:
    """Open vSwitch engine: RSTP and LACP port-channels. The bridge is rebuilt on every
    apply (RSTP reconverges in a couple of seconds). Ports that aren't cabled yet are skipped
    and picked up when the cable lands (the script runs again then)."""
    p = node.get("props", {})
    ports = p.get("ports", {}) or {}
    chans = p.get("channels", {}) or {}
    rstp = bool(p.get("stp"))
    prio = int(p.get("stp_priority") or 32768)
    L = ["#!/bin/sh", f"# generated by netlab for {node['id']} (Open vSwitch) - edit in the web UI (Config tab)",
         "command -v ovs-vsctl >/dev/null || { echo 'openvswitch missing'; exit 1; }",
         "if ! ovs-vsctl --timeout=2 show >/dev/null 2>&1; then",
         "  mkdir -p /var/run/openvswitch /etc/openvswitch /var/log/openvswitch",
         "  [ -f /etc/openvswitch/conf.db ] || ovsdb-tool create /etc/openvswitch/conf.db /usr/share/openvswitch/vswitch.ovsschema",
         "  ovsdb-server --remote=punix:/var/run/openvswitch/db.sock --pidfile --detach --log-file=/var/log/openvswitch/ovsdb-server.log",
         "  ovs-vsctl --no-wait init",
         "  ovs-vswitchd --pidfile --detach --log-file=/var/log/openvswitch/ovs-vswitchd.log",
         "fi",
         "for s in $(ls /sys/class/net | grep '^vlan'); do ip link del \"$s\" 2>/dev/null; done",
         "ovs-vsctl --if-exists del-br br0",
         f"ovs-vsctl add-br br0 -- set bridge br0 rstp_enable={'true' if rstp else 'false'} other_config:rstp-priority={prio}",
         "ip link set br0 up",
         "has() { [ -e /sys/class/net/$1 ]; }"]

    def vlan_args(cfg):
        if (cfg or {}).get("mode") == "trunk":
            native = vlan_id(cfg.get("native") or 1)
            allowed = vlan_list(cfg.get("allowed") or "1-4094")
            tr = "" if len(allowed) == 4094 else _expand(sorted(set(allowed) | {native}))   # OVS wants the native VLAN listed too
            return f"vlan_mode=native-untagged tag={native}" + (f" trunks={tr}" if tr else "")
        return f"vlan_mode=access tag={vlan_id((cfg or {}).get('vlan') or 1)}"

    members = {}
    for ifn, cfg in ports.items():
        if (cfg or {}).get("channel") and re.fullmatch(r"eth[1-9]\d*", ifn):
            members.setdefault(int(cfg["channel"]), []).append(check_if(ifn))
    L.append("for i in $(ls /sys/class/net | grep '^eth' | grep -v '^eth0$'); do")
    skip = " ".join(sorted(m for ms in members.values() for m in ms))
    L.append(f"  case \" {skip} \" in *\" $i \"*) continue ;; esac")
    L.append("  ovs-vsctl add-port br0 \"$i\" -- set port \"$i\" vlan_mode=access tag=1; ip link set \"$i\" up")
    L.append("done")
    for ifn in sorted(ports, key=lambda x: (len(x), x)):
        cfg = ports[ifn] or {}
        if not re.fullmatch(r"eth[1-9]\d*", ifn) or cfg.get("channel"):
            continue
        L.append(f"has {ifn} && ovs-vsctl set port {ifn} {vlan_args(cfg)}")
        if cfg.get("shutdown"):
            L.append(f"has {ifn} && ip link set {ifn} down")
    for n, ms in sorted(members.items()):
        mode = (chans.get(str(n)) or chans.get(n) or {}).get("mode", "active")
        lacp = {"active": "lacp=active", "passive": "lacp=passive", "on": "lacp=off"}.get(mode, "lacp=active")
        bmode = "balance-tcp" if mode != "on" else "balance-slb"
        args = vlan_args(ports.get(f"po{n}"))
        L.append(f"set -- $(for m in {' '.join(sorted(ms))}; do has $m && echo $m; done)")
        L.append(f"if [ $# -ge 2 ]; then ovs-vsctl add-bond br0 po{n} \"$@\" {lacp} bond_mode={bmode} other_config:lacp-time=fast "
                 f"-- set port po{n} {args}; for m in \"$@\"; do ip link set $m up; done")
        L.append(f"elif [ $# -eq 1 ]; then ovs-vsctl add-port br0 $1 -- set port $1 {args}; ip link set $1 up; echo 'po{n}: only one member cabled, running it as a plain port'; fi")
    svi = p.get("svi") or {}
    if svi.get("ip"):
        sv = vlan_id(svi.get("vlan") or 1)
        check_ip(svi["ip"], cidr=True)
        L += [f"ovs-vsctl add-port br0 vlan{sv} tag={sv} -- set interface vlan{sv} type=internal",
              f"ip link set vlan{sv} up", f"ip addr add {svi['ip']} dev vlan{sv}"]
        if svi.get("gateway"):
            L.append(f"ip route replace default via {check_ip(svi['gateway'])}")
    L.append("echo 'switch config applied (Open vSwitch)'")
    return "\n".join(L) + "\n"


def switch_script(node: dict) -> str:
    """Idempotent 802.1Q config for a netlab switch (Linux bridge, vlan_filtering).
    Ports not listed are access VLAN 1, like a factory switch. Re-running it resets
    each port's VLAN membership in place (no detach, so STP does not reconverge)."""
    p = node.get("props", {})
    if p.get("engine") == "ovs":
        return ovs_script(node)
    ports = p.get("ports", {}) or {}
    stp = 1 if p.get("stp") else 0
    L = ["#!/bin/sh", f"# generated by netlab for {node['id']} - edit in the web UI (Config tab)",
         "command -v bridge >/dev/null || { echo 'bridge (iproute2) missing'; exit 1; }",
         "ip link show br0 >/dev/null 2>&1 || ip link add br0 type bridge",
         f"ip link set br0 type bridge vlan_filtering 1 stp_state {stp} priority {int(p.get('stp_priority') or 32768)}",
         "ip link set br0 up",
         "clear_vlans() { for v in $(bridge vlan show dev \"$1\" | awk '{for(i=1;i<=NF;i++) if ($i ~ /^[0-9]+$/) {print $i; break}}'); do bridge vlan del vid \"$v\" dev \"$1\" $2; done; }",
         "for i in $(ls /sys/class/net | grep '^eth' | grep -v '^eth0$'); do",
         "  ip link set \"$i\" master br0 2>/dev/null; ip link set \"$i\" up",
         "  clear_vlans \"$i\"",
         "  bridge vlan add vid 1 dev \"$i\" pvid untagged   # default: access VLAN 1",
         "done"]
    for ifn in sorted(ports, key=lambda x: (len(x), x)):
        check_if(ifn)
        cfg = ports[ifn] or {}
        if not re.fullmatch(r"eth[1-9]\d*", ifn):
            continue                      # port-channels only exist on the Open vSwitch engine
        L.append(f"if [ -e /sys/class/net/{ifn} ]; then")
        L.append(f"  ip link set {ifn} {'down' if cfg.get('shutdown') else 'up'}")
        L.append(f"  clear_vlans {ifn}")
        if cfg.get("mode") == "trunk":
            native = vlan_id(cfg.get("native") or 1)
            allowed = vlan_list(cfg.get("allowed") or "1-4094")
            L.append(f"  # trunk: native {native}, allowed {cfg.get('allowed') or '1-4094'}")
            # contiguous runs as ranges keep the script short for 1-4094
            runs, start, prev = [], None, None
            for v in allowed:
                if start is None:
                    start = prev = v
                elif v == prev + 1:
                    prev = v
                else:
                    runs.append((start, prev)); start = prev = v
            if start is not None:
                runs.append((start, prev))
            for a, b in runs:
                L.append(f"  bridge vlan add vid {a}{'-' + str(b) if b > a else ''} dev {ifn}")
            L.append(f"  bridge vlan add vid {native} dev {ifn} pvid untagged")
        else:
            v = vlan_id(cfg.get("vlan") or 1)
            L.append(f"  bridge vlan add vid {v} dev {ifn} pvid untagged   # access VLAN {v}")
        L.append("fi")
    # management SVI (switch has no routing: ip_forward stays off)
    L += ["for s in $(ls /sys/class/net | grep '^vlan'); do ip link del \"$s\"; done",
          "ip -4 addr flush dev br0",
          "clear_vlans br0 self; bridge vlan add vid 1 dev br0 self pvid untagged"]
    svi = p.get("svi") or {}
    if svi.get("ip"):
        sv = vlan_id(svi.get("vlan") or 1)
        check_ip(svi["ip"], cidr=True)
        if sv == 1:
            L.append(f"ip addr add {svi['ip']} dev br0")
        else:
            L += [f"bridge vlan add vid {sv} dev br0 self",
                  f"ip link add link br0 name vlan{sv} type vlan id {sv}",
                  f"ip link set vlan{sv} up", f"ip addr add {svi['ip']} dev vlan{sv}"]
        if svi.get("gateway"):
            L.append(f"ip route replace default via {check_ip(svi['gateway'])}")
    L.append("echo 'switch config applied'")
    return "\n".join(L) + "\n"


def router_subif_exec(props: dict) -> list[str]:
    """802.1Q subinterfaces (router-on-a-stick): kernel devices, created before FRR configures them."""
    cmds = []
    for si in props.get("subifs", []) or []:
        parent, vid = check_if(si["parent"]), vlan_id(si["vlan"])
        name = check_if(subif_name(si))
        cmds += [f"ip link add link {parent} name {name} type vlan id {vid}", f"ip link set {name} up"]
    return cmds


def subif_name(si: dict) -> str:
    """Subinterface number defaults to the VLAN ID (Gi0/0/0.10 = VLAN 10) but can differ, as on IOS."""
    return f"{si['parent']}.{int(si.get('num') or si['vlan'])}"


def loopback_exec(props: dict) -> list[str]:
    """Loopback1+ are dummy interfaces (Loopback0 is the kernel's lo)."""
    cmds = []
    for n in props.get("loopbacks", []) or []:
        n = int(n)
        if not 1 <= n <= 2147483647:
            raise ValueError(f"bad loopback number {n}")
        cmds += [f"ip link add loop{n} type dummy", f"ip link set loop{n} up"]
    return cmds


