def chrony_conf(props: dict) -> str:
    st = int(((props.get("services") or {}).get("ntp") or {}).get("stratum") or 8)
    if not 1 <= st <= 15:
        raise ValueError("NTP stratum must be 1-15")
    return f"# generated by netlab: NTP server from the local clock\nlocal stratum {st}\nallow all\ndriftfile /var/lib/chrony/drift\n"


FTP_USER_RE = re.compile(r"^[a-z_][a-z0-9_-]{0,15}$")
RESERVED_USERS = {"root", "bin", "daemon", "adm", "nobody", "ftp", "nginx", "dnsmasq", "chrony", "sshd"}


def ftp_users(props: dict) -> list[dict]:
    ftp = (props.get("services") or {}).get("ftp") or {}
    users = ftp.get("users") if ftp.get("users") is not None else [{"user": "cisco", "password": "cisco"}]
    out = []
    for u in users:
        name = str(u.get("user", "")).strip()
        pw = str(u.get("password", ""))
        if not FTP_USER_RE.match(name) or name in RESERVED_USERS:
            raise ValueError(f"FTP user '{name}': lowercase letters, digits, _ and -, up to 16, not a system name")
        if not pw or len(pw) > 64 or any(c in pw for c in ":'\"\\\n"):
            raise ValueError(f"FTP user {name}: password 1-64 characters, no quotes, colons or backslashes")
        out.append({"user": name, "password": pw})
    return out


def vsftpd_conf(props: dict | None = None) -> str:
    # no anonymous login: vsftpd won't chroot anonymous users into a writable directory
    return "\n".join([
        "# generated by netlab: FTP server, files in /srv/ftp (web UI: Services > FTP)",
        "listen=YES", "background=YES", "seccomp_sandbox=NO", "isolate=NO", "isolate_network=NO",
        "local_enable=YES", "write_enable=YES", "local_umask=022", "check_shell=NO",
        "chroot_local_user=YES", "allow_writeable_chroot=YES", "local_root=/srv/ftp",
        "anonymous_enable=NO",
        "pasv_enable=YES", "pasv_min_port=30000", "pasv_max_port=30100",
        "xferlog_enable=YES", "vsftpd_log_file=/var/log/netlab/vsftpd.log", "dual_log_enable=NO",
        "secure_chroot_dir=/var/empty", "pam_service_name=netlab-ftp", ""])


def services_script(props: dict) -> str:
    """Start/stop a server's services to match its props (run at deploy and on Save services)."""
    svc = props.get("services") or {}
    on = lambda k, d=False: bool((svc.get(k) or {}).get("enabled", d))
    L = ["#!/bin/sh", "# generated by netlab - edit the server's Services tab", "need() { command -v $1 >/dev/null || apk add --no-cache $2 >/dev/null; }",
         "pkill dnsmasq 2>/dev/null; sleep 0.2; dnsmasq --conf-file=/etc/netlab/dnsmasq.conf && echo 'dns/dhcp: running'"]
    if on("http", True):
        L.append("mkdir -p /run/nginx; nginx -c /etc/netlab/nginx.conf -s reload 2>/dev/null || nginx -c /etc/netlab/nginx.conf; echo 'http: running'")
    else:
        L.append("nginx -c /etc/netlab/nginx.conf -s stop 2>/dev/null; echo 'http: off'")
    L.append("pkill in.tftpd 2>/dev/null")
    if on("tftp"):
        L.append("need in.tftpd tftp-hpa; mkdir -p /srv/tftp; in.tftpd -4 -l -c -s -u root -p /srv/tftp && echo 'tftp: running (uploads allowed)'")
    L.append("pkill vsftpd 2>/dev/null")
    if on("ftp"):
        L.append("need vsftpd vsftpd; mkdir -p /srv/ftp /var/empty /var/log/netlab; chmod 777 /srv/ftp")
        # only used if vsftpd was built with PAM: plain password check, no /etc/shells test
        L.append("[ -d /etc/pam.d ] && printf 'auth required pam_unix.so\\naccount required pam_unix.so\\nsession required pam_permit.so\\n' > /etc/pam.d/netlab-ftp")
        # FTP accounts are real (shell-less) users whose home is /srv/ftp; the list is rebuilt every time
        L.append("for u in $(sed -n 's/^\\([^:]*\\):.*netlab-ftp.*/\\1/p' /etc/passwd); do deluser $u 2>/dev/null || userdel $u 2>/dev/null; done")
        for u in ftp_users(props):
            L.append(f"(adduser -D -H -h /srv/ftp -s /sbin/nologin -g netlab-ftp {u['user']} 2>/dev/null || useradd -M -d /srv/ftp -s /sbin/nologin -c netlab-ftp {u['user']}) && echo '{u['user']}:{u['password']}' | chpasswd")
        L.append("sleep 0.2; vsftpd /etc/netlab/svc/vsftpd.conf && echo 'ftp: running (port 21)'")
    L.append("pkill rsyslogd 2>/dev/null; rm -f /run/netlab-rsyslogd.pid")
    if on("syslog"):
        L.append("need rsyslogd rsyslog; mkdir -p /var/log/netlab; sleep 0.2; rsyslogd -f /etc/netlab/svc/rsyslog.conf -i /run/netlab-rsyslogd.pid && echo 'syslog: listening on 514/udp+tcp'")
    L.append("pkill chronyd 2>/dev/null")
    if on("ntp"):
        L.append("need chronyd chrony; mkdir -p /var/lib/chrony; sleep 0.2; chronyd -x -f /etc/netlab/svc/chrony.conf && echo 'ntp: serving time'")
    L.append("true")
    return "\n".join(L) + "\n"


def validate_server(props: dict):
    dnsmasq_conf(props); chrony_conf(props); ftp_users(props)


def default_index(node_id: str) -> str:
    return f"<!doctype html><title>{node_id}</title><h1>{node_id}</h1><p>Served from {node_id}.</p>\n"


def write_node_files(lab: dict, node: dict):
    wd = workdir(lab)
    nid = node["id"]
    t = node["type"]
    if t == "switch":
        write_inplace(wd / "configs" / nid / "switch.sh", switch_script(node))
    if t == "router":
        f = wd / "configs" / nid / "frr.conf"
        if not f.exists():
            write_inplace(f, f"frr defaults traditional\nhostname {nid}\n!\n")
        # per-router copies of the shared daemon/vtysh files (directory bind mount)
        for name in ("daemons", "vtysh.conf"):
            write_inplace(wd / "configs" / nid / name, (wd / "configs" / "common" / name).read_text())
    elif t == "firewall":
        write_inplace(wd / "configs" / nid / "fw.nft", firewall.ruleset(node.get("props", {})))
        write_inplace(wd / "configs" / nid / "fw.sh", firewall.script(node))
    elif t == "server":
        d = wd / "configs" / nid
        write_inplace(d / "dnsmasq.conf", dnsmasq_conf(node.get("props", {})))
        write_inplace(d / "nginx.conf", NGINX_CONF)
        write_inplace(d / "svc" / "services.sh", services_script(node.get("props", {})))
        write_inplace(d / "svc" / "rsyslog.conf", RSYSLOG_CONF)
        write_inplace(d / "svc" / "chrony.conf", chrony_conf(node.get("props", {})))
        write_inplace(d / "svc" / "vsftpd.conf", vsftpd_conf(node.get("props", {})))
        (d / "tftp").mkdir(parents=True, exist_ok=True)
        (d / "ftp").mkdir(parents=True, exist_ok=True)
        os.chmod(d / "ftp", 0o777)
        (d / "syslog").mkdir(parents=True, exist_ok=True)
        idx = d / "www" / "index.html"
        http = node.get("props", {}).get("services", {}).get("http", {})
        if http.get("index_html"):
            write_inplace(idx, http["index_html"])
        elif not idx.exists():
            write_inplace(idx, default_index(nid))


def clab_node(lab: dict, node: dict) -> dict:
    if node.get("raw"):
        return node["raw"]
    nid, t, props = node["id"], node["type"], node.get("props", {})
    extra = [l for l in props.get("startup", []) if l.strip()]
    if t == "router":
        # mount the router's config *directory*: FRR's `write memory` writes a temp file and
        # renames it over frr.conf, which a single-file bind mount refuses (EBUSY).
        return {"kind": "linux", "image": props.get("image") or _d("frr_image"),
                "binds": [f"configs/{nid}:/etc/frr"],
                "exec": ROUTER_EXEC + loopback_exec(props) + router_subif_exec(props) + extra}
    if t == "switch":
        pre = ["apk add --no-cache iproute2 openvswitch"] if props.get("engine") == "ovs" else SWITCH_EXEC[:1]
        return {"kind": "linux", "image": _d("alpine_image"), "cmd": "tail -f /dev/null",
                "binds": [f"configs/{nid}/switch.sh:/usr/local/bin/netlab-switch:ro"],
                "exec": pre + SWITCH_EXEC[1:] + extra}
    if t == "firewall":
        return {"kind": "linux", "image": _d("alpine_image"), "cmd": "tail -f /dev/null",
                "binds": [f"configs/{nid}:/etc/netlab"],
                "exec": ["apk add --no-cache nftables iproute2", "sh /etc/netlab/fw.sh"] + extra}
    if t == "pc":
        return {"kind": "linux", "image": props.get("image") or _d("pc_image"), "binds": [DHCP_BIND], "exec": host_ip_exec(props) + extra}
    if t == "server":
        ex = ["apk add --no-cache dnsmasq nginx iproute2 curl", "mkdir -p /run/nginx"]
        ex += host_ip_exec(props)
        ex.append("sh /etc/netlab/svc/services.sh")
        return {"kind": "linux", "image": _d("alpine_image"), "cmd": "tail -f /dev/null",
                "binds": [DHCP_BIND, f"configs/{nid}/dnsmasq.conf:/etc/netlab/dnsmasq.conf",
                          f"configs/{nid}/nginx.conf:/etc/netlab/nginx.conf",
                          f"configs/{nid}/svc:/etc/netlab/svc", f"configs/{nid}/tftp:/srv/tftp", f"configs/{nid}/ftp:/srv/ftp",
                          f"configs/{nid}/syslog:/var/log/netlab", f"configs/{nid}/www:/srv/www"],
                "exec": ex + extra}
    raise ValueError(f"unknown node type '{t}'")


def generate(lab: dict) -> Path:
    wd = workdir(lab)
    wd.mkdir(parents=True, exist_ok=True)
    common = wd / "configs" / "common"
    if not (common / "daemons").exists():
        write_inplace(common / "daemons", DAEMONS)
    if not (common / "vtysh.conf").exists():
        write_inplace(common / "vtysh.conf", "service integrated-vtysh-config\n")
    write_inplace(common / "netlab-dhcp.sh", DHCP_SCRIPT)
    os.chmod(common / "netlab-dhcp.sh", 0o755)
    nodes = {}
    for n in lab["nodes"]:
        if not n.get("raw"):
            write_node_files(lab, n)
        nodes[n["id"]] = clab_node(lab, n)
    topo = {"name": lab["name"],
            "mgmt": {"network": lab.get("mgmt_network") or _d("mgmt_network"), "ipv4-subnet": lab.get("mgmt_subnet") or _d("mgmt_subnet")},
            "topology": {"nodes": nodes,
                         "links": [{"endpoints": [f"{l['a']}:{l['a_if']}", f"{l['b']}:{l['b_if']}"]}
                                   for l in lab["links"]]}}
    if lab.get("raw_kinds"):
        topo["topology"]["kinds"] = lab["raw_kinds"]

    class D(yaml.SafeDumper):
        pass
    D.ignore_aliases = lambda *a: True
    p = topo_path(lab)
    p.write_text("# generated by netlab - edit the lab in the web UI\n" + yaml.dump(topo, Dumper=D, sort_keys=False, width=200))
    return p


def bridges(lab: dict) -> list[str]:
    return [n["id"] for n in lab["nodes"] if (n.get("raw") or {}).get("kind") == "bridge"]


def frr_conf_path(lab: dict, node: dict) -> Path | None:
    if node["type"] != "router":
        return None
    if node.get("raw"):
        for b in node["raw"].get("binds", []):
            src, _, dst = b.partition(":")
            if dst.split(":")[0] == "/etc/frr/frr.conf":
                p = Path(src)
                return p if p.is_absolute() else workdir(lab) / p
        return None
    return workdir(lab) / "configs" / node["id"] / "frr.conf"


# ---------- import an existing containerlab topology ----------

def import_clab(path: str, name: str | None = None) -> dict:
    p = Path(path).expanduser().resolve()
    if not p.is_file():
        raise FileNotFoundError(f"{p} not found on the server")
    topo = yaml.safe_load(p.read_text())
    name = check_name(name or re.sub(r"[^a-z0-9-]", "-", topo["name"].lower())[:31])
    if (lab_dir(name) / "lab.json").exists():
        raise FileExistsError(f"lab '{name}' already exists; delete it first")
    t = topo.get("topology", {})
    kinds = t.get("kinds", {})
    defaults = t.get("defaults", {})
    nodes = []
    names = list(t.get("nodes", {}).keys())
    cols = max(1, int(len(names) ** 0.5 + 0.999))
    for i, nid in enumerate(names):
        raw = dict(t["nodes"][nid] or {})
        kind = raw.get("kind", defaults.get("kind", "linux"))
        image = raw.get("image") or kinds.get(kind, {}).get("image", "") or defaults.get("image", "")
        if kind == "bridge":
            typ = "switch"
        elif "frr" in image:
            typ = "router"
        elif "alpine" in image and any("dnsmasq" in str(x) for x in raw.get("exec", [])):
            typ = "server"
        else:
            typ = "pc"
        raw.setdefault("kind", kind)
        if image and "image" not in raw and kind != "bridge":
            raw["image"] = image
        nodes.append({"id": check_name(nid), "type": typ, "x": 160 * (i % cols), "y": 140 * (i // cols),
                      "props": {}, "raw": raw})
    links = []
    for i, l in enumerate(t.get("links", [])):
        a, b = l["endpoints"]
        an, ai = a.split(":"); bn, bi = b.split(":")
        links.append({"id": f"l{i}", "a": an, "a_if": ai, "b": bn, "b_if": bi, "media": "copper"})
    mg = topo.get("mgmt", {}) or {}
    lab = {"name": name, "workdir": str(p.parent),
           "mgmt_network": mg.get("network") or _d("mgmt_network"), "mgmt_subnet": mg.get("ipv4-subnet") or _d("mgmt_subnet"),
           "nodes": nodes, "links": links, "imported_from": str(p)}
    save(lab)
    return lab
